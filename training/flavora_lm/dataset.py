"""FlavoraLM dataset: a reproducible synthetic corpus of Flavora requests.

Every example is generated by this module from ingredient/cuisine/word
banks original to Flavora — nothing is scraped or copied. Each example
pairs a natural-language request with the structured intent a deterministic
parser would produce, formatted as a chat sequence:

    <BOS><USER> {input} <ASSISTANT> {json target} <EOS>

The generator deliberately varies phrasing, adds misspellings, casual
language, negations, irrelevant words and multi-constraint requests so
the model learns robust extraction, not template matching.
"""

from __future__ import annotations

import json
import random
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, Iterator, List, Optional, Tuple

DATASET_VERSION = "0.1"

INGREDIENTS = [
    "chicken", "rice", "pasta", "tomato", "onion", "garlic", "eggs", "potato",
    "carrot", "bell pepper", "mushrooms", "tofu", "chickpeas", "lentils",
    "spinach", "cheese", "yogurt", "lemon", "salmon", "shrimp", "beef",
    "pork", "beans", "noodles", "bread", "butter", "milk", "cream",
    "peanut butter", "coconut milk", "quinoa", "zucchini", "corn",
]

CUISINES = [
    "italian", "indian", "chinese", "japanese", "mexican", "french",
    "american", "mediterranean", "middle eastern", "african",
]

SPICE_WORDS = {
    "hot": ["spicy", "fiery", "hot and spicy", "with heat", "chili-hot"],
    "medium": ["medium spice", "a little spicy", "mildly spiced"],
    "mild": ["mild", "not spicy", "gentle on spice", "no heat"],
}

CRAVINGS = [
    ("warm and comforting", {"moods": ["comforting"], "temperature": ["warm"]}),
    ("cold and refreshing", {"moods": ["refreshing"], "temperature": ["cold"]}),
    ("crispy and crunchy", {"textures": ["crispy", "crunchy"]}),
    ("creamy", {"textures": ["creamy"]}),
    ("light and fresh", {"flavors": ["fresh"], "satiety": ["light"]}),
    ("hearty and filling", {"satiety": ["filling", "hearty"]}),
    ("cozy homely dinner", {"moods": ["cozy", "homely"]}),
    ("indulgent treat", {"moods": ["indulgent"]}),
    ("smoky", {"flavors": ["smoky"]}),
    ("tangy", {"flavors": ["tangy"]}),
    ("sweet", {"flavors": ["sweet"]}),
    ("savory umami", {"flavors": ["savory", "umami"]}),
]

ALLERGENS = ["peanuts", "dairy", "gluten", "shellfish", "eggs", "soy", "tree nuts"]
AVOID_FOODS = ["mushrooms", "pork", "beef", "cilantro", "olives", "okra", "eggplant"]

TIME_PHRASES = [
    ("in 15 minutes", 15), ("in 20 minutes", 20), ("in 30 minutes", 30),
    ("within 45 minutes", 45), ("under 30 minutes", 30), ("in an hour", 60),
    ("in 90 minutes", 90), ("quick 10 minute meal", 10), ("in 2 hours", 120),
]

OPENERS = [
    "i want", "i'd like", "give me", "can you find", "make me",
    "i feel like", "suggest", "i need", "what about", "how about",
    "looking for", "craving", "whip up", "cook",
]

FILLERS = [
    "please", "thanks", "for dinner tonight", "for lunch", "for my family",
    "after work", "this weekend", "for two people", "if possible", "ok",
]

TYPOS = {
    "chicken": ["chiken", "chciken"],
    "pasta": ["pasta", "pastta"],
    "mushrooms": ["mushrooms", "mushroms"],
    "tomato": ["tomatoe", "tomaato"],
    "spicy": ["spisy", "sypy"],
    "comforting": ["comfoting", "comforting"],
    "minutes": ["minuts", "minites"],
    "allergic": ["alergic", "allergc"],
    "peanuts": ["penuts", "peenuts"],
    "cheese": ["cheeze", "chesse"],
}

IRRELEVANT = [
    "my neighbor said", "by the way i watched a movie", "it is tuesday",
    "the weather is nice", "my cat is sleeping", "i got new shoes",
]


def _maybe_typo(rng: random.Random, word: str, words: List[str]) -> List[str]:
    """Randomly apply a known typo (keeps the label intent unchanged)."""
    if word in TYPOS and rng.random() < 0.12:
        words = list(words)
        words[words.index(word)] = rng.choice(TYPOS[word])
    return words


def _mk_ingredient_phrase(rng: random.Random, items: List[str]) -> str:
    if len(items) == 1:
        return items[0]
    return ", ".join(items[:-1]) + f" and {items[-1]}"


def _mk_intent(
    ingredients: Optional[List[str]] = None,
    time_limit: Optional[int] = None,
    cuisine: Optional[str] = None,
    spice: Optional[str] = None,
    craving: Optional[str] = None,
    craving_signals: Optional[Dict] = None,
    allergies: Optional[List[str]] = None,
    avoid_foods: Optional[List[str]] = None,
    mode: str = "normal",
    meal_type: Optional[str] = None,
) -> Dict:
    out: Dict = {"intent": "recommend"}
    if ingredients:
        out["ingredients"] = ingredients
    if time_limit:
        out["timeLimit"] = time_limit
    if cuisine:
        out["cuisine"] = cuisine
    if spice:
        out["spicePreference"] = spice
    if craving:
        out["craving"] = craving
    if craving_signals:
        out["cravingSignals"] = craving_signals
    if allergies:
        out["allergies"] = allergies
    if avoid_foods:
        out["avoidFoods"] = avoid_foods
    if mode != "normal":
        out["mode"] = mode
    if meal_type:
        out["mealType"] = meal_type
    return out


def _compose_text(rng: random.Random, parts: List[str]) -> str:
    opener = rng.choice(OPENERS)
    body = " ".join(p for p in parts if p)
    filler = rng.choice(FILLERS) if rng.random() < 0.3 else ""
    noise = rng.choice(IRRELEVANT) + "." if rng.random() < 0.06 else ""
    text = f"{opener} {body} {filler}".strip()
    if noise:
        text = f"{noise} {text}"
    return text[0].upper() + text[1:] + "."


def generate_examples(count: int, seed: int = 42) -> Iterator[Tuple[str, Dict]]:
    """Yield (text, intent) pairs with wide variation."""
    rng = random.Random(seed)
    made = 0
    while made < count:
        kind = rng.random()

        if kind < 0.34:
            # Ingredients + optional time + optional cuisine.
            items = rng.sample(INGREDIENTS, rng.randint(1, 4))
            items = _maybe_typo(rng, items[0], items) if items else items
            time_phrase, t = (None, None)
            if rng.random() < 0.6:
                time_phrase, t = rng.choice(TIME_PHRASES)
            cuisine = rng.choice(CUISINES) if rng.random() < 0.3 else None
            parts = [
                f"something with {_mk_ingredient_phrase(rng, items)}",
                time_phrase or "",
                f"{cuisine} style" if cuisine else "",
            ]
            yield _compose_text(rng, parts), _mk_intent(
                ingredients=items, time_limit=t, cuisine=cuisine,
                mode="food_waste" if rng.random() < 0.4 else "normal",
            )
        elif kind < 0.52:
            # Craving-driven.
            craving, signals = rng.choice(CRAVINGS)
            extra_ing = [rng.choice(INGREDIENTS)] if rng.random() < 0.4 else None
            parts = [f"something {craving}"]
            if extra_ing:
                parts.append(f"with {extra_ing[0]}")
            yield _compose_text(rng, parts), _mk_intent(
                ingredients=extra_ing, craving=craving.split(" and ")[0], craving_signals=signals,
            )
        elif kind < 0.68:
            # Allergy / avoid-food extraction (safety-critical data).
            allergen = rng.choice(ALLERGENS)
            avoid = rng.choice(AVOID_FOODS)
            items = rng.sample(INGREDIENTS, 2)
            styles = [
                f"i am allergic to {allergen} give me something with {_mk_ingredient_phrase(rng, items)}",
                f"allergic to {allergen} here what can i eat with {items[0]}",
                f"no {allergen} for me i have {items[0]}",
                f"i can not eat {allergen} want {items[0]} quick",
            ]
            text = rng.choice(styles)
            if rng.random() < 0.5:
                text += f" and i do not want {avoid}"
                yield text, _mk_intent(ingredients=items, allergies=[allergen], avoid_foods=[avoid])
            else:
                yield text, _mk_intent(ingredients=items, allergies=[allergen])
        elif kind < 0.80:
            # Avoid-food / dislikes (no allergy).
            avoid = rng.choice(AVOID_FOODS)
            items = [rng.choice(INGREDIENTS)]
            text = f"i don't want {avoid} but something with {items[0]} would be great"
            yield _compose_text(rng, [f"no {avoid}, something with {items[0]}"]), _mk_intent(
                ingredients=items, avoid_foods=[avoid],
            )
        elif kind < 0.90:
            # Spice preference.
            spice = rng.choice(list(SPICE_WORDS.keys()))
            word = rng.choice(SPICE_WORDS[spice])
            items = [rng.choice(INGREDIENTS)]
            time_phrase, t = rng.choice(TIME_PHRASES)
            yield _compose_text(rng, [f"{word} {items[0]} dish", time_phrase]), _mk_intent(
                ingredients=items, time_limit=t, spice=spice,
            )
        else:
            # Modes: food waste / budget.
            if rng.random() < 0.5:
                items = rng.sample(INGREDIENTS, rng.randint(2, 5))
                yield _compose_text(rng, [
                    f"use up {_mk_ingredient_phrase(rng, items)}",
                    rng.choice(["from the fridge", "leftovers", "before they expire"]),
                ]), _mk_intent(ingredients=items, mode="food_waste")
            else:
                items = rng.sample(INGREDIENTS, 2)
                yield _compose_text(rng, ["cheap budget meal", f"with {items[0]}"]), _mk_intent(
                    ingredients=items, mode="budget",
                )
        made += 1


def format_example(tokenizer, text: str, intent: Dict, max_len: int) -> List[int]:
    """Encode one chat-formatted example, truncating so EOS is always last.

    Layout: [BOS, USER, *prompt, ASSISTANT, *target, EOS].
    """
    prompt_ids = tokenizer.encode(text, add_special=False)
    target_ids = tokenizer.encode(json.dumps(intent, separators=(",", ":"), sort_keys=True), add_special=False)
    ids = (
        [tokenizer.bos_id, tokenizer.user_id]
        + prompt_ids
        + [tokenizer.assistant_id]
        + target_ids
    )
    return ids[: max_len - 1] + [tokenizer.eos_id]


def target_start_index(tokenizer, text: str, max_len: int) -> int:
    """First target position for a formatted example: the ASSISTANT marker.

    Training masks the loss on everything before this index so gradient
    focuses on the structured completion (the deterministic JSON suffix)
    instead of the unpredictable natural-language prompt words. Inference
    is unaffected — this only changes which positions contribute to the
    cross-entropy loss. Truncation mirrors format_example.
    """
    prompt_ids = tokenizer.encode(text, add_special=False)
    start = 2 + len(prompt_ids)  # [BOS, USER] + prompt → ASSISTANT index
    return min(start, max_len - 1)


def write_jsonl(path: str | Path, examples: List[Tuple[str, Dict]]) -> None:
    p = Path(path)
    p.parent.mkdir(parents=True, exist_ok=True)
    with p.open("w", encoding="utf-8") as f:
        for text, intent in examples:
            f.write(json.dumps({"input": text, "target": intent}, ensure_ascii=False) + "\n")


def read_jsonl(path: str | Path) -> List[Tuple[str, Dict]]:
    out: List[Tuple[str, Dict]] = []
    for line in Path(path).read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        obj = json.loads(line)
        out.append((obj["input"], obj["target"]))
    return out
